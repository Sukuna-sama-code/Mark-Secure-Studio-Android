const STORAGE_KEY = 'marksecure_active_gradient_id';

export const getSavedWebGradient = (): WebGradient => {
  try {
    const savedId = localStorage.getItem(STORAGE_KEY);
    if (savedId) {
      const match = WEB_GRADIENTS.find((g) => g.id === savedId);
      if (match) return match;
    }
  } catch {
    // ignore
  }
  return WEB_GRADIENTS[4]; // Young Passion (#005) default
};

export const saveWebGradient = (gradient: WebGradient) => {
  try {
    localStorage.setItem(STORAGE_KEY, gradient.id);
  } catch {
    // ignore
  }
};
